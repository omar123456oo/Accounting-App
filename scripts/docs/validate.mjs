#!/usr/bin/env node
// Documentation checks and generated index/coverage.
//
//   node scripts/docs/validate.mjs           check, then rewrite DOCUMENTATION_INDEX.md and DOCUMENTATION_COVERAGE.md
//   node scripts/docs/validate.mjs --check   check only; exit 1 on any error or if the index/coverage are stale
//
// Checks: required front matter, duplicate ids, broken relative links, template placeholders left in real documents,
// and "last_verified" present when verification_status claims verification.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const DOCS = join(ROOT, 'docs');
const CHECK = process.argv.includes('--check');
const read = (p) => readFileSync(p, 'utf8');
const rel = (p) => relative(DOCS, p).split('\\').join('/');
const walk = (dir, out = []) => {
  for (const n of readdirSync(dir).sort()) {
    if (n.startsWith('.')) continue;
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out); else if (n.endsWith('.md')) out.push(p);
  }
  return out;
};

const REQUIRED = ['title', 'id', 'document_type', 'status', 'verification_status'];
const VERIFICATION = ['verified', 'source-scanned', 'implemented-not-runtime-verified', 'partial', 'planned', 'unverified'];
const GENERATED_INDEX = 'DOCUMENTATION_INDEX.md';
const GENERATED_COVERAGE = 'DOCUMENTATION_COVERAGE.md';

function frontMatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([\w_]+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1');
  }
  return out;
}

const files = walk(DOCS);
const managed = []; // documents that carry front matter and are not templates
const legacy = [];
const errors = [];
for (const f of files) {
  const r = rel(f);
  if (r.startsWith('templates/') || r.startsWith('superpowers/') || r.startsWith('plans/')) continue;
  const text = read(f);
  const fm = frontMatter(text);
  if (!fm) { legacy.push(r); continue; }
  managed.push({ path: r, fm, text });
}

const ids = new Map();
for (const d of managed) {
  for (const k of REQUIRED) if (!d.fm[k]) errors.push(`${d.path}: missing front matter "${k}"`);
  if (d.fm.verification_status && !VERIFICATION.includes(d.fm.verification_status)) errors.push(`${d.path}: unknown verification_status "${d.fm.verification_status}" (use ${VERIFICATION.join(', ')})`);
  if (d.fm.verification_status === 'verified' && (!d.fm.last_verified || d.fm.last_verified === 'null')) errors.push(`${d.path}: verification_status is "verified" but last_verified is empty`);
  if (d.fm.id) { if (ids.has(d.fm.id)) errors.push(`${d.path}: duplicate id "${d.fm.id}" (also ${ids.get(d.fm.id)})`); ids.set(d.fm.id, d.path); }
  if (/\{\{[^}]+\}\}|\bTODO\b|<fill in>/.test(d.text.replace(/```[\s\S]*?```/g, ''))) errors.push(`${d.path}: contains an unfilled placeholder ({{...}}, TODO or <fill in>)`);
}

// Relative links (ignore http(s), mailto, pure anchors, and anything inside code fences/spans)
for (const f of files) {
  const r = rel(f);
  if (r.startsWith('superpowers/') || r.startsWith('plans/') || r.startsWith('templates/')) continue;
  const text = read(f).replace(/```[\s\S]*?```/g, '').replace(/`[^`\n]*`/g, '');
  for (const m of text.matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)) {
    const target = m[1];
    if (/^(https?:|mailto:|#)/.test(target)) continue;
    const path = decodeURIComponent(target.split('#')[0]);
    if (!path) continue;
    if (!existsSync(resolve(dirname(f), path))) errors.push(`${r}: broken link → ${target}`);
  }
}

// ---- index ------------------------------------------------------------------------------------------------------------
const inv = JSON.parse(read(join(DOCS, '.inventory.json')));
const byType = new Map();
for (const d of managed) { const t = d.fm.document_type; if (!byType.has(t)) byType.set(t, []); byType.get(t).push(d); }
const row = (d) => `| [${d.fm.title}](${d.path}) | \`${d.fm.id}\` | ${d.fm.status} | ${d.fm.verification_status} | ${d.fm.last_verified && d.fm.last_verified !== 'null' ? d.fm.last_verified : '—'} |`;
let index = `---
title: "Documentation Index"
id: "SYS-INDEX-001"
document_type: "index"
status: "generated"
verification_status: "source-scanned"
generated_by: "scripts/docs/validate.mjs"
---

# Documentation Index

> Generated by \`node scripts/docs/validate.mjs\`. Do not edit by hand.

`;
for (const [type, docs] of [...byType].sort(([a], [b]) => a.localeCompare(b))) {
  if (['index', 'coverage'].includes(type)) continue;
  index += `## ${type}\n\n| Document | ID | Status | Verification | Last verified |\n|---|---|---|---|---|\n${docs.sort((a, b) => a.path.localeCompare(b.path)).map(row).join('\n')}\n\n`;
}
index += `## Existing documents (no front matter yet)\n\nThese predate the documentation system. They are listed so nothing is lost; they have not been audited against the code.\n\n${legacy.filter((p) => ![GENERATED_INDEX, GENERATED_COVERAGE].includes(p)).map((p) => `- [${p}](${p})`).join('\n')}\n`;

// ---- coverage ---------------------------------------------------------------------------------------------------------
const moduleDocs = managed.filter((d) => d.path.startsWith('modules/'));
const moduleText = moduleDocs.map((d) => d.text).join('\n');
const guideDirs = new Set(moduleDocs.map((d) => d.path.split('/')[1]));
const pct = (a, b) => (b === 0 ? 'n/a' : `${((a / b) * 100).toFixed(1)}%`);
const endpointDescribed = inv.endpointList.filter((e) => moduleText.includes(e.replace(/^(\w+) /, '$1 `')) || moduleText.includes('`' + e + '`') || moduleText.includes(e)).length;
const modelDescribed = inv.modelList.filter((m) => new RegExp(`\\b${m}\\b`).test(moduleText)).length;
const routeDescribed = inv.routeList.filter((r) => r !== '/' && moduleText.includes('`' + r + '`')).length;
const featureGuides = inv.featureDirs.filter((d) => guideDirs.has(d)).length;
const verifiedDocs = moduleDocs.filter((d) => d.fm.verification_status === 'verified').length;
const rows = [
  ['Frontend feature folders with a module guide', inv.featureDirs.length, featureGuides],
  ['Backend endpoints described in a module guide', inv.endpoints, endpointDescribed],
  ['Mongoose models described in a module guide', inv.models, modelDescribed],
  ['Frontend routes described in a module guide', inv.routes, routeDescribed],
];
let coverage = `---
title: "Documentation Coverage"
id: "SYS-COVERAGE-001"
document_type: "coverage"
status: "generated"
verification_status: "source-scanned"
generated_by: "scripts/docs/validate.mjs"
---

# Documentation Coverage

> Generated by \`node scripts/docs/validate.mjs\`. Counts of discovered items come from \`docs/.inventory.json\` (written by \`scripts/docs/scan.mjs\`). "Described" means the item's name, route or URL appears in a module guide under \`docs/modules/\`. The generated references (API catalog, data dictionary, route map, permissions matrix) list **every** discovered item, but they are inventories, not explanations, so they are not counted here.

**Formula:** documentation coverage = described discovered items ÷ discovered items × 100%. Nothing nonexistent is counted in the denominator.

| Category | Discovered | Described in a module guide | Coverage |
|---|---|---|---|
${rows.map(([n, t, d]) => `| ${n} | ${t} | ${d} | ${pct(d, t)} |`).join('\n')}

**Coverage is not accuracy.** Verification is reported separately: ${verifiedDocs} of ${moduleDocs.length} module documents have \`verification_status: verified\` (${pct(verifiedDocs, moduleDocs.length)}). A document is only marked verified when the behaviour it describes was exercised (a passing test or a run), and the date is recorded.

## Items found by the scan that need review

- Backend endpoints whose path or permission could not be resolved automatically: ${inv.endpointsNeedingReview} (listed in [API_CATALOG](API_CATALOG.md#needs-review)).
- Frontend permissions with no backend counterpart (mock-API modules): see [PERMISSIONS_MATRIX](PERMISSIONS_MATRIX.md).

## Not yet documented (frontend feature folders)

${inv.featureDirs.filter((d) => !guideDirs.has(d)).map((d) => `- \`features/${d}\``).join('\n') || '- none'}

## Totals from the scan

${Object.entries({ endpoints: inv.endpoints, models: inv.models, 'model fields': inv.modelFields, permissions: inv.permissions, roles: inv.roles, 'frontend routes': inv.routes, 'navigation items': inv.navItems, 'frontend feature folders': inv.featureDirs.length, 'mock-API source files': inv.mockSourceFiles }).map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`;

const write = (name, content) => {
  const p = join(DOCS, name);
  if (CHECK) { if (!existsSync(p) || read(p) !== content) errors.push(`${name}: stale; run node scripts/docs/validate.mjs`); }
  else writeFileSync(p, content);
};
write(GENERATED_INDEX, index);
write(GENERATED_COVERAGE, coverage);

if (errors.length) { console.error(errors.map((e) => `✘ ${e}`).join('\n')); console.error(`\n${errors.length} documentation problem(s).`); process.exit(1); }
console.log(`Documentation OK: ${managed.length} managed documents, ${legacy.length} legacy, ${ids.size} unique ids.`);
